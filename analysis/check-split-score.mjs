import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {callTool,stateOf} from '../harness/session.mjs';
import {geometryMetrics,loadBoard} from '../harness/board.mjs';
import {sha,readJson,writeJson} from '../harness/io.mjs';
const source=path.resolve('results/k60-crossing-preflight-fixed'),ws=path.resolve('results/split-score-preflight');
if(fs.existsSync(ws))throw Error('Use a fresh integration output');
fs.cpSync(source,ws,{recursive:true});fs.writeFileSync(path.join(ws,'tools.jsonl'),'');
const state=stateOf(ws),saved=readJson(path.join(ws,'c001.json')),expected=saved.metrics;
const {problem}=loadBoard(state);
saved.metrics=geometryMetrics(problem,saved.layout);saved.scored=false;saved.needsScore=true;saved.eligible=false;
writeJson(path.join(ws,'c001.json'),saved);state.candidates.c001={...state.candidates.c001,metrics:saved.metrics,scored:false,eligible:false};state.best=null;writeJson(path.join(ws,'session.json'),state);
const immutable=s=>sha(JSON.stringify({layout:s.layout,placement:s.placement,engine:s.engine,scope:s.scope})),before=immutable(saved);
assert.match((await callTool(ws,'submit',{candidate:'c001'})).error,/Submit requires/);
assert.match((await callTool(ws,'score',{candidate:'c000'})).error,/Only a produced/);
const result=await callTool(ws,'score',{candidate:'c001'});
assert.equal(result.error,undefined);assert.deepEqual(result.metrics,expected);
assert.equal(immutable(readJson(path.join(ws,'c001.json'))),before);
assert.equal(stateOf(ws).placeCalls,state.placeCalls);assert.equal(result.eligible,false);assert.equal(stateOf(ws).best,null);
writeJson(path.join(ws,'verification.json'),{passed:true,poseAndEngineHash:before,placeCalls:state.placeCalls,metrics:result.metrics,scoreSeconds:result.seconds,checks:['unscored submit rejected','random baseline score rejected','score equals original independent routing configuration','poses/engine/scope exact','place quota unchanged','illegal candidate remains ineligible']});
console.log(JSON.stringify({passed:true,seconds:result.seconds,metrics:result.metrics}));
